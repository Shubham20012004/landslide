import { Gauge, ImageDown, Power, PowerOff, Trash2 } from "lucide-react";
import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { ConfusionMatrix, ImportanceBars } from "../charts";
import { Async, Badge, Button, Card, ConfirmDialog, EmptyState, KV, MetricCard, Modal, Notice, PageHeader, Table } from "../components/ui";
import { useAction, useApi } from "../hooks/useApi";
import { api } from "../services/api";
import type { ModelInfo } from "../types";
import { fmtDateTime, fmtNum, fmtPct, LABEL_SOURCE_TEXT, riskColor } from "../utils/format";

const METRIC_ROWS: [keyof ModelInfo["summary_metrics"], string][] = [
  ["f1_macro", "Macro F1"], ["recall_macro", "Macro recall"], ["precision_macro", "Macro precision"],
  ["f1_weighted", "Weighted F1"], ["accuracy", "Accuracy"], ["balanced_accuracy", "Balanced accuracy"], ["majority_baseline_accuracy", "Majority-class baseline"],
];

function ModelDetail({ m, onChanged }: { m: ModelInfo; onChanged: () => void }) {
  const mt = m.metrics!;
  const [confirm, setConfirm] = useState<"activate" | "delete" | null>(null);
  const act = useAction();
  return (
    <div className="space-y-4">
      <Card title={<span className="flex flex-wrap items-center gap-2">Model v{m.version} · {m.name} {m.is_active && <Badge tone="green">ACTIVE</Badge>} {m.is_synthetic && <Badge tone="violet">trained on SYNTHETIC data</Badge>}</span>}
        subtitle={`Trained ${fmtDateTime(m.created_at)} on ${m.dataset_name}`}
        actions={<>
          {m.is_active
            ? <Button size="sm" icon={PowerOff} loading={act.busy} onClick={() => act.run(async () => { await api.deactivate(m.id); onChanged(); })}>Deactivate</Button>
            : <Button size="sm" variant="primary" icon={Power} onClick={() => setConfirm("activate")}>Activate</Button>}
          <Button size="sm" variant="danger" icon={Trash2} disabled={m.is_active} title={m.is_active ? "Deactivate first" : undefined} onClick={() => setConfirm("delete")}>Delete</Button>
        </>}>
        {m.is_synthetic && <Notice tone="sim" className="mb-3" title="Pipeline test only">These metrics come from a synthetic fixture generated by the same rules that labelled it. They demonstrate that training and evaluation work; they are NOT findings about the prototype or about landslides.</Notice>}
        {m.label_source === "esp32_rule_engine" && <Notice tone="warning" className="mb-3">Labels came from the ESP32 rule engine. High scores mean the model reproduces those rules, not that it independently predicts slope failure.</Notice>}
        <div className="grid grid-cols-2 gap-3 md:grid-cols-4 xl:grid-cols-7">
          {METRIC_ROWS.map(([k, label]) => <MetricCard key={k} label={label} value={fmtPct(mt[k as keyof typeof mt] as number)} tone={k === "majority_baseline_accuracy" ? "muted" : undefined} />)}
        </div>
        <p className="mt-2 text-xs text-slate-500">Prioritise macro-F1 and per-class recall: with imbalanced classes, accuracy can look high while rare CRITICAL cases are missed. Compare every score with the majority-class baseline.</p>
        {act.error && <Notice tone="danger" className="mt-2">{act.error}</Notice>}
      </Card>

      <div className="grid grid-cols-1 gap-4 xl:grid-cols-2">
        <Card title="Confusion matrix (test set)" actions={mt.plots?.confusion_matrix && <a href={api.artifactUrl(mt.plots.confusion_matrix)} target="_blank" rel="noreferrer"><Button size="sm" icon={ImageDown}>PNG</Button></a>}>
          <ConfusionMatrix labels={mt.confusion_matrix.labels} matrix={mt.confusion_matrix.matrix} />
        </Card>
        <Card title="Per-class performance">
          <Table head={["Class", "Precision", "Recall", "F1", "Support"]}>
            {mt.per_class.map((c) => (
              <tr key={c.label}>
                <td className="px-3 py-2 font-semibold" style={{ color: riskColor(c.label) }}>{c.label}</td>
                <td className="px-3 py-2 font-mono">{fmtNum(c.precision, 3)}</td>
                <td className={`px-3 py-2 font-mono ${c.support && c.recall < 0.6 ? "text-amber-300" : ""}`}>{fmtNum(c.recall, 3)}</td>
                <td className="px-3 py-2 font-mono">{fmtNum(c.f1, 3)}</td>
                <td className="px-3 py-2 font-mono">{c.support}</td>
              </tr>
            ))}
          </Table>
          {mt.evaluation_warnings.map((w, i) => <Notice key={i} tone="warning" className="mt-2">{w}</Notice>)}
          <details className="mt-3 text-xs text-slate-400"><summary className="cursor-pointer">Classification report (text)</summary><pre className="mt-2 overflow-x-auto rounded bg-ink-950 p-3 font-mono">{mt.classification_report_text}</pre></details>
        </Card>
        <Card title="Feature importance — mean decrease in impurity" subtitle="Computed on training data; can favour high-cardinality features." actions={mt.plots?.feature_importance && <a href={api.artifactUrl(mt.plots.feature_importance)} target="_blank" rel="noreferrer"><Button size="sm" icon={ImageDown}>PNG</Button></a>}>
          <ImportanceBars data={mt.feature_importance_mdi} />
        </Card>
        <Card title="Permutation importance (test set, macro-F1 drop)" subtitle="More reliable: how much the held-out score falls when a feature is shuffled (±std over 5 repeats).">
          <ImportanceBars data={mt.permutation_importance} color="#199e70" />
        </Card>
      </div>

      <Card title="Training configuration and provenance">
        <KV cols={3} items={[
          ["Dataset", m.dataset_name], ["Dataset SHA-256", <span className="font-mono text-[11px]" title={m.dataset_hash}>{m.dataset_hash.slice(0, 16)}…</span>],
          ["Label source", m.label_source ? LABEL_SOURCE_TEXT[m.label_source] ?? m.label_source : "—"],
          ["Target", m.target], ["Features", m.features.join(", ")], ["Classes", m.classes.join(", ")],
          ["Split strategy", m.split_strategy], ["Rows (train / test)", `${m.n_train} / ${m.n_test}`], ["Training time", `${fmtNum(m.training_duration_sec, 2)} s (fit ${fmtNum(mt.fit_time_sec, 2)} s)`],
          ...Object.entries(m.hyperparameters).map(([k, v]) => [k, String(v ?? "None")] as [string, string]),
          ["Artifact", <span className="font-mono text-[11px]">{m.artifact_file}</span>], ["Artifact SHA-256", <span className="font-mono text-[11px]">{m.artifact_sha256.slice(0, 16)}…</span>], ["Training run", m.run_id ? `#${m.run_id}` : "—"],
        ]} />
        {m.split_details && "test_groups" in m.split_details && (
          <p className="mt-3 text-xs text-slate-400">Held-out experiments: {(m.split_details.test_groups as string[]).join(", ")} · Training experiments: {(m.split_details.train_groups as string[]).length}</p>
        )}
        {m.warnings.length > 0 && <div className="mt-3 space-y-1.5">{m.warnings.map((w, i) => <Notice key={i} tone={/SYNTHETIC/.test(w) ? "sim" : "warning"}>{w}</Notice>)}</div>}
      </Card>

      <ConfirmDialog open={confirm === "activate"} title={`Activate model v${m.version}?`} confirmLabel="Activate" busy={act.busy} onCancel={() => setConfirm(null)}
        onConfirm={() => act.run(async () => { await api.activate(m.id); setConfirm(null); onChanged(); })}>
        <p>The active model's output is shown on the AI Predictions page <b>alongside</b> the ESP32 state. It never replaces the ESP32's rule-based risk state or controls the device. Any other active model will be deactivated.</p>
        {m.is_synthetic && <Notice tone="sim" className="mt-3">This model was trained on SYNTHETIC data; its predictions are for demonstrating the workflow only.</Notice>}
      </ConfirmDialog>
      <ConfirmDialog open={confirm === "delete"} danger title={`Delete model v${m.version}?`} confirmLabel="Delete permanently" busy={act.busy} onCancel={() => setConfirm(null)}
        onConfirm={() => act.run(async () => { await api.deleteModel(m.id); setConfirm(null); onChanged(); })}>
        The registry entry, joblib artifact and evaluation plots will be removed. This cannot be undone.
      </ConfirmDialog>
    </div>
  );
}

export default function ModelEvaluation() {
  const [params, setParams] = useSearchParams();
  const models = useApi(() => api.models(), []);
  const [sel, setSel] = useState<number | null>(params.get("model") ? Number(params.get("model")) : null);
  const [cmp, setCmp] = useState<number[]>([]);
  const [cmpOpen, setCmpOpen] = useState(false);
  useEffect(() => { if (sel === null && models.data?.models.length) setSel(models.data.models[0].id); }, [models.data, sel]);
  const detail = useApi(() => api.model(sel!), [sel], null, sel !== null);
  const compare = useApi(() => api.compare(cmp), [cmpOpen], null, cmpOpen && cmp.length > 1);
  const changed = () => { models.reload(); detail.reload(); };

  return (
    <>
      <PageHeader icon={Gauge} title="Model Evaluation & Registry" subtitle="Every trained model is versioned with its dataset hash, features, hyperparameters, split strategy and held-out metrics. Activation is always an explicit user action."
        actions={<Button disabled={cmp.length < 2} onClick={() => setCmpOpen(true)}>Compare selected ({cmp.length})</Button>} />
      <Card title="Model registry">
        <Async state={models}>{(d) => d.models.length === 0 ? <EmptyState icon={Gauge} title="No trained models" action={<Link to="/training"><Button variant="primary">Train a model</Button></Link>} /> : (
          <Table head={["", "Version", "Name", "Dataset", "Split", "Macro F1", "Macro recall", "Accuracy", "Baseline", "Status", ""]}>
            {d.models.map((m) => (
              <tr key={m.id} className={sel === m.id ? "bg-sky-500/5" : "hover:bg-ink-750/50"}>
                <td className="px-3 py-2"><input type="checkbox" aria-label={`compare v${m.version}`} checked={cmp.includes(m.id)} onChange={(e) => setCmp(e.target.checked ? [...cmp, m.id] : cmp.filter((x) => x !== m.id))} /></td>
                <td className="px-3 py-2 font-mono">v{m.version}</td>
                <td className="px-3 py-2">{m.name} {m.is_synthetic && <Badge tone="violet">synthetic</Badge>}</td>
                <td className="max-w-[180px] truncate px-3 py-2 text-xs">{m.dataset_name}</td>
                <td className="px-3 py-2 text-xs">{m.split_strategy}</td>
                <td className="px-3 py-2 font-mono">{fmtNum(m.summary_metrics.f1_macro, 3)}</td>
                <td className="px-3 py-2 font-mono">{fmtNum(m.summary_metrics.recall_macro, 3)}</td>
                <td className="px-3 py-2 font-mono">{fmtNum(m.summary_metrics.accuracy, 3)}</td>
                <td className="px-3 py-2 font-mono text-slate-500">{fmtNum(m.summary_metrics.majority_baseline_accuracy, 3)}</td>
                <td className="px-3 py-2">{m.is_active ? <Badge tone="green">active</Badge> : <Badge>inactive</Badge>}</td>
                <td className="px-3 py-2 text-right"><Button size="sm" onClick={() => { setSel(m.id); setParams({ model: String(m.id) }); }}>Details</Button></td>
              </tr>
            ))}
          </Table>
        )}</Async>
      </Card>
      {sel !== null && <div className="mt-4"><Async state={detail}>{(m) => <ModelDetail m={m} onChanged={changed} />}</Async></div>}
      <Modal open={cmpOpen} onClose={() => setCmpOpen(false)} title="Model comparison" wide>
        <Async state={compare}>{(d) => (
          <Table head={["Metric", ...d.models.map((m) => `v${m.version}${m.is_synthetic ? " (synthetic)" : ""}`)]}>
            {[["Dataset", (m: ModelInfo) => m.dataset_name], ["Split", (m: ModelInfo) => m.split_strategy], ["Features", (m: ModelInfo) => m.features.length], ["Train/test rows", (m: ModelInfo) => `${m.n_train}/${m.n_test}`],
              ...METRIC_ROWS.map(([k, l]) => [l, (m: ModelInfo) => fmtNum(m.summary_metrics[k], 3)] as const),
              ...["SAFE", "WATCH", "WARNING", "CRITICAL"].map((c) => [`Recall ${c}`, (m: ModelInfo) => fmtNum(m.metrics?.per_class.find((p) => p.label === c)?.recall, 3)] as const),
              ["n_estimators", (m: ModelInfo) => String(m.hyperparameters.n_estimators)], ["max_depth", (m: ModelInfo) => String(m.hyperparameters.max_depth ?? "None")], ["class_weight", (m: ModelInfo) => String(m.hyperparameters.class_weight)],
            ].map(([label, fn]) => (
              <tr key={label as string}><td className="px-3 py-1.5 text-slate-400">{label as string}</td>{d.models.map((m) => <td key={m.id} className="px-3 py-1.5 font-mono">{(fn as (m: ModelInfo) => string | number)(m)}</td>)}</tr>
            ))}
          </Table>
        )}</Async>
      </Modal>
    </>
  );
}
